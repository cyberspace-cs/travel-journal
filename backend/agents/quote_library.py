# 合并所有金句
QUOTE_LIBRARY = {
    "travel": TRAVEL_QUOTES,
    "daily": DAILY_QUOTES,
    "food": FOOD_QUOTES,
    "emotion": EMOTION_QUOTES,
    "work": WORK_QUOTES,
}


def get_quote(category: str = "daily", keywords: list = None):
    """
    从金句库里随机选一个最相关的金句
    :param category: 分类：travel/daily/work/food/emotion
    :param keywords: 关键词列表，用来匹配
    :return: 金句
    """
    # 先找对应分类的金句
    quotes = QUOTE_LIBRARY.get(category, QUOTE_LIBRARY["daily"])

    # 如果有关键词，找最相关的
    if keywords:
        best_quote = quotes[0]
        best_score = 0
        for q in quotes:
            score = sum(1 for kw in keywords if kw in q)
            if score > best_score:
                best_score = score
                best_quote = q
        return best_quote

    # 没有关键词就随机选一个
    import random
    return random.choice(quotes)


def get_total_count():
    """总金句数"""
    return sum(len(v) for v in QUOTE_LIBRARY.values())


if __name__ == "__main__":
    print(f"金句库总数：{get_total_count()} 句")
    for k, v in QUOTE_LIBRARY.items():
        print(f"  {k}: {len(v)} 句")

    print("\n随机示例：")
    print(f"  旅行: {get_quote('travel')}")
    print(f"  日常: {get_quote('daily')}")
    print(f"  美食: {get_quote('food')}")
